import { deflateSync } from "zlib"

function crc32(buf: Buffer): number {
  let crc = 0xffffffff
  for (let i = 0; i < buf.length; i++) {
    crc ^= buf[i]
    for (let j = 0; j < 8; j++) {
      crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0)
    }
  }
  return (crc ^ 0xffffffff) >>> 0
}

function makeChunk(type: string, data: Buffer): Buffer {
  const typeData = Buffer.concat([Buffer.from(type), data])
  const length = Buffer.alloc(4)
  length.writeUInt32BE(data.length, 0)
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(typeData), 0)
  return Buffer.concat([length, typeData, crc])
}

function createPng(
  width: number,
  height: number,
  r: number,
  g: number,
  b: number,
  label: string
): Buffer {
  const signature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])

  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(width, 0)
  ihdr.writeUInt32BE(height, 4)
  ihdr[8] = 8
  ihdr[9] = 2
  ihdr[10] = 0
  ihdr[11] = 0
  ihdr[12] = 0

  const rawData = Buffer.alloc(height * (1 + width * 3))
  for (let y = 0; y < height; y++) {
    const offset = y * (1 + width * 3)
    rawData[offset] = 0

    const factor = 1 - y / height * 0.3
    const pr = Math.floor(r * factor)
    const pg = Math.floor(g * factor)
    const pb = Math.floor(b * factor)

    for (let x = 0; x < width; x++) {
      const px = offset + 1 + x * 3
      rawData[px] = pr
      rawData[px + 1] = pg
      rawData[px + 2] = pb
    }
  }

  const labelChars = label.toUpperCase()
  const charW = 5
  const charH = 7
  const totalW = labelChars.length * (charW + 1)
  const startX = Math.floor((width - totalW) / 2)
  const startY = Math.floor(height / 2 - charH / 2)
  const scale = Math.max(1, Math.floor(width / 120))

  const GLYPHS: Record<string, number[]> = {
    A: [0x04, 0x0a, 0x11, 0x1f, 0x11, 0x11, 0x11],
    B: [0x1e, 0x11, 0x11, 0x1e, 0x11, 0x11, 0x1e],
    C: [0x0e, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0e],
    D: [0x1e, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1e],
    E: [0x1f, 0x10, 0x10, 0x1e, 0x10, 0x10, 0x1f],
    F: [0x1f, 0x10, 0x10, 0x1e, 0x10, 0x10, 0x10],
    G: [0x0e, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0e],
    H: [0x11, 0x11, 0x11, 0x1f, 0x11, 0x11, 0x11],
    I: [0x0e, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0e],
    J: [0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0c],
    K: [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
    L: [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1f],
    M: [0x11, 0x1b, 0x15, 0x15, 0x11, 0x11, 0x11],
    N: [0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11],
    O: [0x0e, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0e],
    P: [0x1e, 0x11, 0x11, 0x1e, 0x10, 0x10, 0x10],
    Q: [0x0e, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0d],
    R: [0x1e, 0x11, 0x11, 0x1e, 0x14, 0x12, 0x11],
    S: [0x0e, 0x11, 0x10, 0x0e, 0x01, 0x11, 0x0e],
    T: [0x1f, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
    U: [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0e],
    V: [0x11, 0x11, 0x11, 0x11, 0x0a, 0x0a, 0x04],
    W: [0x11, 0x11, 0x11, 0x15, 0x15, 0x1b, 0x11],
    X: [0x11, 0x11, 0x0a, 0x04, 0x0a, 0x11, 0x11],
    Y: [0x11, 0x11, 0x0a, 0x04, 0x04, 0x04, 0x04],
    Z: [0x1f, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1f],
    " ": [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
    "0": [0x0e, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0e],
    "1": [0x04, 0x0c, 0x04, 0x04, 0x04, 0x04, 0x0e],
    "2": [0x0e, 0x11, 0x01, 0x06, 0x08, 0x10, 0x1f],
    "3": [0x0e, 0x11, 0x01, 0x06, 0x01, 0x11, 0x0e],
    "4": [0x02, 0x06, 0x0a, 0x12, 0x1f, 0x02, 0x02],
    "5": [0x1f, 0x10, 0x1e, 0x01, 0x01, 0x11, 0x0e],
    "6": [0x06, 0x08, 0x10, 0x1e, 0x11, 0x11, 0x0e],
    "7": [0x1f, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
    "8": [0x0e, 0x11, 0x11, 0x0e, 0x11, 0x11, 0x0e],
    "9": [0x0e, 0x11, 0x11, 0x0f, 0x01, 0x02, 0x0c],
    "-": [0x00, 0x00, 0x00, 0x1f, 0x00, 0x00, 0x00],
    "+": [0x00, 0x04, 0x04, 0x1f, 0x04, 0x04, 0x00],
    "&": [0x0c, 0x12, 0x14, 0x08, 0x15, 0x12, 0x0d],
  }

  for (let ci = 0; ci < labelChars.length; ci++) {
    const ch = labelChars[ci]
    const glyph = GLYPHS[ch]
    if (!glyph) continue

    for (let gy = 0; gy < charH; gy++) {
      for (let gx = 0; gx < charW; gx++) {
        if (glyph[gy] & (0x10 >> gx)) {
          for (let sy = 0; sy < scale; sy++) {
            for (let sx = 0; sx < scale; sx++) {
              const px = startX + ci * (charW + 1) * scale + gx * scale + sx
              const py = startY + gy * scale + sy
              if (px >= 0 && px < width && py >= 0 && py < height) {
                const offset = py * (1 + width * 3) + 1 + px * 3
                rawData[offset] = 255
                rawData[offset + 1] = 255
                rawData[offset + 2] = 255
              }
            }
          }
        }
      }
    }
  }

  const compressed = deflateSync(rawData)

  return Buffer.concat([
    signature,
    makeChunk("IHDR", ihdr),
    makeChunk("IDAT", compressed),
    makeChunk("IEND", Buffer.alloc(0)),
  ])
}

export function generateProductImage(
  category: string,
  label: string
): { base64: string; mimeType: string; size: number; name: string } {
  const colors: Record<string, [number, number, number]> = {
    pakaian: [66, 133, 244],
    sepatu: [234, 134, 46],
    tas: [52, 168, 83],
    elektronik: [142, 86, 178],
    aksesoris: [219, 68, 55],
  }

  const [r, g, b] = colors[category] || [128, 128, 128]
  const png = createPng(400, 400, r, g, b, label)
  const slug = label.toLowerCase().replace(/[^a-z0-9]+/g, "-")

  return {
    base64: png.toString("base64"),
    mimeType: "image/png",
    size: png.length,
    name: `${slug}.png`,
  }
}
